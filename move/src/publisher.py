class RobotController(Node):
    """Drives the robot, tracks its position error, and flags obstacles."""

    def __init__(self):
        super().__init__('robot_controller')

        # Publish to /error when the position delta exceeds this (TASK 2.3).
        # This is a starting value -- justify whatever you settle on.
        self.error_thresh = 0.5

        # ---- TASK 1.2: publisher that drives the robot ---------------------
        # Which topic moves the robot? Find it first (TASK 1.1), then uncomment.
        
        self.move_pub = self.create_publisher(Twist, '/cmd_vel', 10)

        # ---- TASK 1.3: the path you chose ----------------------------------
        # Pick a route that gets the robot around the wall, and represent it
        # however you think is best -- a list of waypoints, a sequence of
        # timed velocity commands, a parametric curve, something else.
        #
        # Document HERE why you chose this path and this representation.
        # That reasoning is a large part of what we are evaluating.


        """
        I've chosen to represent the path around the wall via waypoints that only store positional and rotational targets.
        This route has 4 points, including a starting pose, intermediate waypoints, and an end goal.
        The reason for this idea is to abstract the high-level goals/objectives of the robot's pathfinding into simple positional targets, 
        and allow lower-level implementations to construct their own trajectories, constraints, and path following algorithms. I could also pair this
        with additional data per point, such as a desired velocity target, but from watching some Lunabotics videos, every robot drive action starts
        without being in motion and ends up in a state without motion. The only use case for velocity targets (probably) is if you want the robot to
        shovel moon dirt while driving, meaning the robot would have its velocity constrained to not go too fast.
        
        For example, this high-level path could be generated by a pathfinding algorithm that utilizes LiDAR data to find the shortest 3d path between
        obstacles to an objective. This gives whatever low level implementation of pathfollowing and trajectory generation we choose
        lots of freedom to do what they want with this data. Furthermore, this representation is super generalizable and easy to modify, visualize, 
        and analyze for anyone that may work with this data. It also gives a lot more flexibility and robustness compared to a time-parametrized,
        velocity-parametrized, or parametric curve, because if for example the robot gets knocked off course, it can just find the next point on the
        path to drive to, and generate a new trajectory on the fly based on the remaining points, instead of following a rigidly defined definition of 
        a path. 

        An example of a low-level implementation could just be a simple drive-to-point PID controller for our robot (i'm assuming it's a tank drive). 
        The robot would rotate via PID to a desired heading, drive forward with a PID loop based off odometry, 
        reach the desired position, and rotate one last time to match the end rotational target. For every point in the path, the robot would just use 
        this drive-to-point to complete the path. This is already a pretty robust (albeit simple) way to complete autonomous routines, as the PID on the 
        heading and translation could help account for wheel slip/tread slip, and hopefully the localization can help ensure our robot actually gets to 
        the correct pose.

        Another example of a low-level implementation could be a trajectory generator. This could take in the path of points and create a 
        trajectory based on any number of techniques (splines, polynomials, etc). Then you would use a differential PID controller to follow each of 
        the position, velocity, and acceleration values at each time step of the path. One issue with this however, is that if the robot ever falls behind/
        doens't meet the position, velocity, and acceleration values at a certian time step, then the PID controllers may fight with each other & create
        unintended behavior.

        For more advanced paths however, one could add in control points for Bezier curves for more precise control of pathing as well, but that would require 
        adding more poses and data to store the control points.
        """

        # Anyways thanks for reading all that, here's the implementation lol:
        initial = Pose(position=Point(x=0.0, y=0.0, z=0.0), quaternion=Quaternion()) 
        point1  = Pose(position=Point(x=5.0, y=7.5, z=0.0), quaternion=Quaternion())
        end     = Pose(position=Point(x=12.5, y=0.0, z=0.0), quaternion=Quaternion())
        self.path = [initial, point1, end]
        self.generate_spline(self.path, 2.0)

        # Then drive it on a timer:
        self.prev_yaw   = 0.0
        self.start_time = self.get_clock().now()
        self.move_timer = self.create_timer(0.1, self.send_move_cmd)

        # ---- TASK 2.2: subscriber for the robot's 6D pose ------------------
        # One of the two onboard sensors reports 6D data. Find it (TASK 2.1).
        #
        self.robot_pos_sub = self.create_subscription(
            Imu,
            "/imu",
            self.on_robot_pos,
            qos_profile_sensor_data,
        )
        self.ground_truth = self.create_subscription(
                    Odometry,
                    "/model/vehicle_blue/odometry",
                    self.calculate_delta,
                    qos_profile_sensor_data,
                )
        self.pose = self.pose = Pose(
                        position=Point(x=0.0, y=0.0, z=0.0),
                        orientation=Quaternion(w=1.0, x=0.0, y=0.0, z=0.0)
                    ) # starts at (0,0,0) with yaw of 0 degrees (assuming no roll or pitch)
        self.pose_timestamp = 0.0
        self.velocity = Twist() # starts with 0 translational and rotational velocity

        # ---- TASK 2.3: where the measured-vs-actual error goes -------------
        self.error_pub = self.create_publisher(Float64, '/error', 10)
        self.imu_pose_pub = self.create_publisher(Pose, "/imu_pose", 10)
        #
        # Hint: ground truth for "actual" is published by the simulator on the
